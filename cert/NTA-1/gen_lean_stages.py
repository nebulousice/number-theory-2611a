#!/usr/bin/env python3
"""Generate lean/Pipeline/BanerjeeSmoot/Stages.lean: the intermediate coefficient lists of the
Lean computation (one list per application of opF / opH), as literals.

The literals are untrusted hints: Lean re-checks every step `op L_c = L_(c+1)` in the kernel
(`decide +kernel`), so an error here can only make the Lean build fail, never pass wrongly.
Splitting the computation into stages keeps the kernel's recursion depth small.

Usage: python gen_lean_stages.py <output .lean path>
"""
import sys

N = 54


def mul_one_plus(m, s):
    return [s[i] + (s[i - m] if i >= m else 0) for i in range(len(s))]


def op_f(s):
    for k in range(54):
        s = mul_one_plus(k + 1, s)
    return s


def op_h(s):
    for k in range(54):
        for j in range(6):
            s = mul_one_plus((k + 1) * 2 ** j, s)
    return s


def chain(op, s, n):
    out = [s]
    for _ in range(n):
        s = op(s)
        out.append(s)
    return out


def lit(L):
    return "[" + ", ".join(str(x) for x in L) + "]"


def lean_list_of_lists(name, Ls, doc):
    body = ",\n  ".join(lit(L) for L in Ls)
    return f"/-- {doc} -/\ndef {name} : List (List Nat) := [\n  {body}]\n"


init = [1] + [0] * N
f36 = chain(op_f, init, 36)
h1 = chain(op_h, f36[-1], 1)
f40 = chain(op_f, init, 40)
h5 = chain(op_h, f40[-1], 5)
assert h1[-1][54] == 62043410886974649205238011198
assert h5[-1][54] == 66134580699742235651549220246110

parts = [
    "-- Generated by targets/number-theory-2611a/cert/NTA-1/gen_lean_stages.py. Do not edit by hand.\n"
    "-- Untrusted data: every step is re-checked by the kernel in Main.lean.\n",
    "set_option maxRecDepth 100000\n",
    "namespace BanerjeeSmoot\n",
    lean_list_of_lists("chainF36", f36, "Coefficient lists of F54^c, c = 0..36."),
    lean_list_of_lists("chainH1", h1, "F54^36 * H54^c, c = 0..1."),
    lean_list_of_lists("chainF40", f40, "Coefficient lists of F54^c, c = 0..40."),
    lean_list_of_lists("chainH5", h5, "F54^40 * H54^c, c = 0..5."),
    "end BanerjeeSmoot\n",
]
with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(parts))
print("wrote", sys.argv[1])
